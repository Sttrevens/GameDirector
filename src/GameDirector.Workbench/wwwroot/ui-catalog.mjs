const preferenceKey='gd.language';
let language='en';
export function chooseLanguage({languages=[],storage=()=>globalThis.localStorage}={}){
  try{const saved=storage()?.getItem(preferenceKey);if(saved==='en'||saved==='zh-CN')return saved;}catch{/* private/blocked storage */}
  return Array.from(languages||[]).some(locale=>/^zh/i.test(locale))?'zh-CN':'en';
}
export function saveLanguage(value,storage=()=>globalThis.localStorage){
  language=value==='zh-CN'?'zh-CN':'en';
  try{storage()?.setItem(preferenceKey,language);}catch{/* the current session still switches */}
  return language;
}
export function t(key,args={},locale=language){
  const value=messages[locale]?.[key]??messages.en[key];
  if(value===undefined)return key;
  return value.replace(/\{(\w+)\}/g,(match,name)=>args?.[name]===undefined?match:String(args[name]));
}
export function serverMessage(code,english,args={},locale=language){
  const key='server.'+code;
  return Object.hasOwn(messages.en,key)?t(key,args,locale):english;
}
export function renderLanguage(document,locale){
  language=locale==='zh-CN'?'zh-CN':'en';document.documentElement.lang=language;
  for(const element of document.querySelectorAll('[data-i18n]'))element.textContent=t(element.dataset.i18n);
  for(const attribute of ['placeholder','aria-label','title'])
    for(const element of document.querySelectorAll('[data-i18n-'+attribute+']'))
      element.setAttribute(attribute,t(element.getAttribute('data-i18n-'+attribute)));
}
