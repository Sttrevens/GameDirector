        public static string SelectLanguage(string preference, SystemLanguage system)
        {
            if (preference == "en" || preference == "zh-CN") return preference;
            return system == SystemLanguage.Chinese || system == SystemLanguage.ChineseSimplified || system == SystemLanguage.ChineseTraditional ? "zh-CN" : "en";
        }
        public static string Language => SelectLanguage(EditorPrefs.GetString(PreferenceKey, ""), Application.systemLanguage);
        public static string T(string key, params object[] args)
        {
            if (!Tables[Language].TryGetValue(key, out var text)) return key;
            return args.Length == 0 ? text : string.Format(CultureInfo.InvariantCulture, text, args);
        }
        public static string State(string state) => Tables["en"].ContainsKey("state." + state) ? T("state." + state) : state;
        public static string ServerMessage(string code, string english, JToken args = null)
        {
            if (code == null || !Tables[Language].TryGetValue("server." + code, out var text)) return english;
            if (args is JObject values)
                foreach (var property in values.Properties()) text = text.Replace("{" + property.Name + "}", property.Value.ToString());
            return text;
        }
        public static void Toggle() => Set(Language == "en" ? "zh-CN" : "en");
        private static void Set(string language)
        {
            if (language == null) EditorPrefs.DeleteKey(PreferenceKey); else EditorPrefs.SetString(PreferenceKey, language);
            UnityEditorInternal.InternalEditorUtility.RepaintAllViews();
        }
        [MenuItem("Window/GameDirector/Language/Automatic")] public static void Automatic() => Set(null);
        [MenuItem("Window/GameDirector/Language/English")] public static void English() => Set("en");
        [MenuItem("Window/GameDirector/Language/Chinese (Simplified)")] public static void Chinese() => Set("zh-CN");

